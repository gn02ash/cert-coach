using CertCoach.Application.Ai;
using CertCoach.Domain.Certifications;
using CertCoach.Domain.Documents;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using NpgsqlTypes;
using Pgvector;

namespace CertCoach.Infrastructure.Persistence.Configurations;

internal sealed class DocumentConfiguration : IEntityTypeConfiguration<Document>
{
    public void Configure(EntityTypeBuilder<Document> builder)
    {
        builder.HasKey(d => d.Id);
        builder.Property(d => d.Id).ValueGeneratedNever();
        builder.Ignore(d => d.Title);
        builder.Property(d => d.CustomTitle).HasMaxLength(Document.MaxTitleLength);
        builder.Property(d => d.ExtractedTitle).HasMaxLength(Document.MaxTitleLength);
        builder.Property(d => d.FileName).HasMaxLength(255);
        builder.Property(d => d.ContentHash).HasMaxLength(64);
        builder.Property(d => d.Error).HasMaxLength(500);
        builder.Property(d => d.EmbeddingModel).HasMaxLength(100);
        builder.Ignore(d => d.StorageKey);

        builder.HasIndex(d => new { d.OwnerId, d.ContentHash }).IsUnique();

        // The worker's claim query looks for pending documents that are due.
        builder.HasIndex(d => new { d.Status, d.NextAttemptAt });

        builder.HasOne<Certification>()
            .WithMany()
            .HasForeignKey(d => d.CertificationId)
            .OnDelete(DeleteBehavior.SetNull);
    }
}

internal sealed class DocumentChunkConfiguration : IEntityTypeConfiguration<DocumentChunk>
{
    /// <summary>Generated by PostgreSQL from the section and text; only raw SQL reads it, so it is a shadow property.</summary>
    public const string SearchVector = "SearchVector";

    public void Configure(EntityTypeBuilder<DocumentChunk> builder)
    {
        builder.ToTable("document_chunks");
        builder.HasKey(c => c.Id);
        builder.Property(c => c.Id).ValueGeneratedNever();
        builder.HasIndex(c => new { c.DocumentId, c.Index }).IsUnique();
        builder.HasIndex(c => c.OwnerId);

        builder.HasOne<Document>()
            .WithMany()
            .HasForeignKey(c => c.DocumentId)
            .OnDelete(DeleteBehavior.Cascade);

        builder.Property(c => c.Embedding)
            .HasColumnType($"vector({AiCapabilities.EmbeddingDimensions})")
            .HasConversion(v => new Vector(v), v => v.ToArray(), new ValueComparer<float[]>(
                (a, b) => ReferenceEquals(a, b) || (a != null && b != null && a.SequenceEqual(b)),
                v => v.Length,
                v => v.ToArray()));

        // Cosine distance, matching how the embedding models are meant to be compared.
        builder.HasIndex(c => c.Embedding)
            .HasMethod("hnsw")
            .HasOperators("vector_cosine_ops");

        builder.Property<NpgsqlTsVector>(SearchVector)
            .HasComputedColumnSql("to_tsvector('english', heading_path || ' ' || text)", stored: true);
        builder.HasIndex(SearchVector).HasMethod("GIN");
    }
}
